#!/usr/bin/env python3
"""Check every relative link in the repository's Markdown.

This repo is mostly documentation, and it is documentation that points at itself:
five edition directories, each with its own README, docs, plugin skill and
reference files, all cross-linking to the root and to each other. Moving or
renaming a file breaks those links silently -- nothing fails, the link just stops
resolving, and the next reader finds a 404 instead of the contract they were sent
to read.

Only relative links are checked. External URLs are left to a human: this must
stay offline and deterministic so it can sit inside the canonical gate.

    python tools/check_links.py
"""

from __future__ import annotations

import re
import subprocess
import sys
from pathlib import Path
from urllib.parse import unquote

ROOT = Path(__file__).resolve().parent.parent

# Target: <angle form with spaces> or a run that may hold balanced (parentheses); optional title.
TARGET = r"""(<[^>\n]*>|(?:[^()\s]|\([^()\s]*\))+)(?:\s+(?:"[^"]*"|'[^']*'))?"""
LINK_PATTERN = re.compile(r"(?<!!)\[[^\]]*\]\(\s*" + TARGET + r"\s*\)")
IMAGE_PATTERN = re.compile(r"!\[[^\]]*\]\(\s*" + TARGET + r"\s*\)")
FENCE_PATTERN = re.compile(r"^ {0,3}(`{3,}|~{3,})")
INLINE_CODE_PATTERN = re.compile(r"(`+)(?!`).+?(?<!`)\1(?!`)")
HTML_SRC_PATTERN = re.compile(r"""(?is)<img[^>]+src=["']([^"']+)["']""")

SKIP_PREFIXES = ("http://", "https://", "mailto:", "tel:", "#", "$")

# Generated by the scheduled checks into the workspace, never committed.
SKIP_NAMES = {
    "upstream-review-report.md",
    "dependency-freshness-report.md",
}


def iter_documents() -> list[Path]:
    """Every tracked or non-ignored new Markdown file.

    `git ls-files` rather than a glob: it inherits `.gitignore`, so a local
    ignored scratch file stays outside the gate; new source docs are checked.
    """
    result = subprocess.run(
        # -z: otherwise git quotes non-ASCII names ("æ.md") and the path no longer exists.
        ["git", "-C", str(ROOT), "ls-files", "-z", "--cached", "--others", "--exclude-standard", "*.md"],
        capture_output=True,
        text=True,
        encoding="utf-8",
        check=False,
    )
    if result.returncode != 0:
        return sorted(
            path for path in ROOT.rglob("*.md") if ".git" not in path.parts
        )
    return sorted(
        ROOT / name
        for name in result.stdout.split("\0")
        # A tracked file deleted from the working tree is still listed by --cached.
        if name and Path(name).name not in SKIP_NAMES and (ROOT / name).is_file()
    )


def missing_target(path: Path, target: str) -> str | None:
    """Return a description of the broken link, or None when it resolves."""
    target = target.strip()
    if target.startswith("<") and ">" in target:
        target = target[1:target.index(">")]  # angle form: spaces belong to the path
        path_part = target
    else:
        # A link may carry a title: [text](./file.md "Title").
        path_part = target.split()[0] if target.split() else ""
    if not path_part or path_part.startswith(SKIP_PREFIXES):
        return None
    file_part = unquote(path_part.split("#", 1)[0])
    if not file_part:
        return None
    resolved = (path.parent / file_part).resolve()
    if resolved.exists():
        return None
    try:
        shown = resolved.relative_to(ROOT)
    except ValueError:
        shown = resolved
    return f"{target} -> missing {shown}"


def strip_code(text: str) -> str:
    """Drop fenced blocks and inline code: Markdown shown as an example is not a link."""
    kept: list[str] = []
    fence = ""
    for line in text.splitlines():
        m = FENCE_PATTERN.match(line)
        if fence:
            if m and m.group(1)[0] == fence[0] and len(m.group(1)) >= len(fence) and not line.strip().strip(fence[0]):
                fence = ""
        elif m:
            fence = m.group(1)
        else:
            kept.append(INLINE_CODE_PATTERN.sub("", line))
    return "\n".join(kept)


def check_document(path: Path) -> list[str]:
    problems: list[str] = []
    text = strip_code(path.read_text(encoding="utf-8"))
    for pattern in (LINK_PATTERN, IMAGE_PATTERN, HTML_SRC_PATTERN):
        for match in pattern.finditer(text):
            problem = missing_target(path, match.group(1))
            if problem:
                problems.append(problem)
    return problems


def main() -> int:
    documents = iter_documents()
    if not documents:
        print("FAIL: no Markdown source files were found")
        return 1

    failures = 0
    for path in documents:
        relative = path.relative_to(ROOT)
        problems = check_document(path)
        if problems:
            failures += 1
            for problem in problems:
                print(f"FAIL {relative}: {problem}")
        else:
            print(f"OK   {relative}")

    print(f"\n{len(documents)} Markdown files checked, {failures} with broken links.")
    return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(main())
